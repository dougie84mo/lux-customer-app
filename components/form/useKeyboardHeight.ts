// Height of the on-screen keyboard while it is up (0 otherwise), on both
// platforms. Generalises useIosKeyboardHeight() from OrientationDialog.
//
// iOS reports the `Will` events (the height arrives before the animation, so a
// sheet can move with the keyboard); Android only has the `Did` events.
import { useEffect, useState } from 'react';
import { Keyboard, Platform } from 'react-native';

export function useKeyboardHeight(): number {
  const [height, setHeight] = useState(0);
  useEffect(() => {
    const ios = Platform.OS === 'ios';
    const show = Keyboard.addListener(ios ? 'keyboardWillShow' : 'keyboardDidShow', (e) =>
      setHeight(e.endCoordinates.height),
    );
    const hide = Keyboard.addListener(ios ? 'keyboardWillHide' : 'keyboardDidHide', () => setHeight(0));
    return () => {
      show.remove();
      hide.remove();
    };
  }, []);
  return height;
}
